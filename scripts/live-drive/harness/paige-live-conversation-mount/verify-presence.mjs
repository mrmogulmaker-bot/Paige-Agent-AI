import { resolvePlaywright, buildLaunchOptions } from "../../live-drive.mjs";
import fs from "node:fs/promises";
import path from "node:path";
const out = path.resolve(process.env.LIVE_EVIDENCE_DIR || "docs/evidence/ui-delivery/assets/paige-live-conversation/presence-recovery");
await fs.mkdir(out, { recursive: true });
const { chromium } = await resolvePlaywright();
const browser = await chromium.launch(buildLaunchOptions());
const context = await browser.newContext({ viewport: { width: 1366, height: 768 }, recordVideo: { dir: out, size: { width: 1366, height: 768 } } });
const page = await context.newPage();
const report = { evidenceClass: "local real-component + actual locally generated audio playback; NOT provider or authenticated tenant proof", states: [], outputSamples: [], checks: [] };
const check = (name, value) => { report.checks.push({ name, pass: !!value }); if (!value) throw new Error(name); };
for (const state of ["ready", "listening", "thinking", "working", "held", "interrupted", "disconnected"]) {
  await page.goto(`http://127.0.0.1:5227/?theme=dark&presence=${state}`);
  const shape = page.locator("[data-presence-shape]").first();
  const first = await shape.getAttribute("d");
  await page.waitForTimeout(500);
  check(`${state} baseline shape changes`, first !== await shape.getAttribute("d"));
  check(`${state} no invented audio`, Number(await page.locator(".paige-presence svg").getAttribute("data-energy")) === 0);
  await page.screenshot({ path: path.join(out, `state-${state}.png`) });
  report.states.push({ state, audio: "absent", fixture: true });
}
await page.goto("http://127.0.0.1:5227/?theme=dark");
await page.getByRole("button", { name: "Talk live with Paige" }).click();
await page.waitForSelector('[data-presence-state="unavailable"]');
const sampleAmbient = () => page.locator(".paige-presence svg").evaluate(svg => ({
  time: performance.now(), path: svg.querySelector("[data-presence-shape]").getAttribute("d"),
  drift: parseFloat(svg.style.getPropertyValue("--presence-drift")),
  energy: Number(svg.dataset.energy),
}));
const ambientFirst = await sampleAmbient();
await page.waitForTimeout(2000);
const ambientLast = await sampleAmbient();
const a = ambientFirst.path.match(/-?\d+\.\d+/g).map(Number), b = ambientLast.path.match(/-?\d+\.\d+/g).map(Number);
const maxShapeDelta = Math.max(...a.map((n, i) => Math.abs(n-b[i])));
check("unavailable motion visibly changes silhouette within two seconds", maxShapeDelta > 6);
check("unavailable ambient motion has no fake audio", ambientFirst.energy === 0 && ambientLast.energy === 0);
report.ambientMotion = { elapsedMs: ambientLast.time-ambientFirst.time, maxShapeDelta, driftDelta: Math.abs(ambientLast.drift-ambientFirst.drift) };
await page.screenshot({ path: path.join(out, "state-unavailable.png") });
await page.evaluate(() => window.fixturePlay());
await page.waitForSelector('[data-presence-state="speaking"]');
for (let i = 0; i < 14; i++) {
  await page.waitForTimeout(120);
  report.outputSamples.push(Number(await page.locator(".paige-presence svg").getAttribute("data-energy")));
}
check("actual played audio produces positive analyzer energy", report.outputSamples.some((n) => n > .05));
check("actual output energy changes", new Set(report.outputSamples).size > 3);
await page.screenshot({ path: path.join(out, "state-speaking-local-audio.png") });
await page.getByRole("button", { name: "Hold", exact: true }).click();
await page.waitForSelector('[data-presence-state="held"]');
check("hold zeros energy", Number(await page.locator(".paige-presence svg").getAttribute("data-energy")) === 0);
await page.getByRole("button", { name: "Resume", exact: true }).click();
await page.waitForSelector('[data-presence-state="speaking"]');
await page.getByRole("button", { name: "Interrupt", exact: true }).click();
await page.waitForSelector('[data-presence-state="interrupted"]');
check("interrupt zeros energy", Number(await page.locator(".paige-presence svg").getAttribute("data-energy")) === 0);
await page.evaluate(() => window.fixturePlay());
await page.waitForSelector('[data-presence-state="speaking"]');
await page.getByRole("button", { name: "Mute", exact: true }).click();
check("mute exits speaking", await page.locator('[data-presence-state="speaking"]').count() === 0);
await page.getByRole("button", { name: "Minimize", exact: true }).last().click();
check("same unsaved composer returns", await page.getByLabel("Message Paige").inputValue() === "Help me review this plan.");
await page.screenshot({ path: path.join(out, "state-minimized.png") });
await page.emulateMedia({ reducedMotion: "reduce" });
await page.goto("http://127.0.0.1:5227/?theme=light&presence=ready");
await page.waitForSelector('[data-motion="reduced"]');
const shape = page.locator("[data-presence-shape]").first();
const first = await shape.getAttribute("d");
await page.waitForTimeout(600);
check("reduced motion keeps sculptural shape still", first === await shape.getAttribute("d"));
await page.screenshot({ path: path.join(out, "state-reduced-motion.png") });
await page.setViewportSize({ width: 390, height: 844 });
await page.goto("http://127.0.0.1:5227/?theme=light&card=choice");
await page.getByRole("button", { name: "Talk live with Paige" }).click();
check("compact has no horizontal overflow", await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth && document.querySelector(".plc-stage").scrollWidth <= innerWidth));
check("compact open in window remains reachable", await page.getByRole("button", { name: "Open in window" }).isVisible());
check("compact main is the only vertical scroll owner", await page.evaluate(() => getComputedStyle(document.querySelector(".plc-stage__main")).overflowY === "auto" && getComputedStyle(document.querySelector(".plc-transcript")).overflowY === "visible" && getComputedStyle(document.querySelector(".plc-card-layer")).overflowY === "visible"));
await page.screenshot({ path: path.join(out, "compact-390x844.png") });
const video = page.video();
await page.setViewportSize({ width: 1366, height: 768 });
await page.goto("http://127.0.0.1:5227/?theme=dark&long=1");
await page.getByRole("button", { name: "Talk live with Paige" }).click();
await page.locator(".plc-transcript").hover();
await page.mouse.wheel(0, -950);
await page.waitForTimeout(250);
const anchor = () => page.evaluate(() => {
  const region = document.querySelector(".plc-transcript"), top = region.getBoundingClientRect().top;
  const item = [...region.querySelectorAll("[data-paige-message-id]")].find((el) => el.getBoundingClientRect().bottom > top);
  return { key: item?.getAttribute("data-paige-message-anchor-key"), offset: item?.getBoundingClientRect().top - top };
});
const before = await anchor();
await page.evaluate(() => window.fixtureAppend());
await page.waitForTimeout(150);
check("Live deliberate anchor survives streaming", JSON.stringify(before) === JSON.stringify(await anchor()));
await page.evaluate(() => window.fixtureRehydrate());
await page.waitForTimeout(150);
check("Live semantic anchor survives persisted IDs", JSON.stringify(before) === JSON.stringify(await anchor()));
await page.getByRole("button", { name: "Minimize", exact: true }).last().click();
await page.getByRole("button", { name: "Talk live with Paige" }).click();
await page.waitForTimeout(150);
check("Live exact anchor survives minimize/restore", JSON.stringify(before) === JSON.stringify(await anchor()));
await page.getByRole("button", { name: "Minimize", exact: true }).last().click();
await page.evaluate(() => window.fixtureThread(null));
await page.waitForTimeout(150);
await page.evaluate(() => window.fixtureThread("00000000-0000-4000-8000-000000000002"));
await page.waitForTimeout(150);
await page.getByRole("button", { name: "Talk live with Paige" }).click();
await page.waitForTimeout(150);
check("history selection after New preserves saved reading anchor", JSON.stringify(before) === JSON.stringify(await anchor()));
check("explicit Jump to latest offered", await page.getByRole("button", { name: "Jump to latest" }).isVisible());
await page.getByRole("button", { name: "Jump to latest" }).click();
check("explicit jump returns exact bottom", await page.locator(".plc-transcript").evaluate((el) => Math.abs(el.scrollHeight - el.clientHeight - el.scrollTop) < 1));
await context.close();
await video.saveAs(path.join(out, "presence-motion-local-audio.webm"));
await video.delete();
await browser.close();
await fs.writeFile(path.join(out, "motion-results.json"), JSON.stringify(report, null, 2));
console.log(JSON.stringify(report, null, 2));
